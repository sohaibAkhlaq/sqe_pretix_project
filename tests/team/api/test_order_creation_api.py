    def test_bva_quantity_points_from_generator(self, event_endpoints, admin_headers, generated_data):
        """
        TC-API-02g: Verifies 3-Point BVA Quantity Points loaded dynamically from generator.
        Points: min-1 (0), min (1), min+1 (2), nominal (5), max-1 (9), max (10), max+1 (11).
        """
        bva_points = generated_data["bva_quantity"]
        assert len(bva_points) == 7, f"Expected 7 3-point BVA points, got {len(bva_points)}"

        point_map = {p["point"]: p for p in bva_points}
        assert point_map["min - 1"]["quantity"] == 0 and not point_map["min - 1"]["valid"]
        assert point_map["min"]["quantity"] == 1 and point_map["min"]["valid"]
        assert point_map["max"]["quantity"] == 10 and point_map["max"]["valid"]
        assert point_map["max + 1"]["quantity"] == 11 and not point_map["max + 1"]["valid"]
