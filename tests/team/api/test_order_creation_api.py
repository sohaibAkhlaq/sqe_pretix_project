"""
API Integration Tests for Order Creation (Workflow A).
Exclusively consumes test datasets generated by tools/datagen/generator.py.
Verifies Equivalence Partitioning (EP), 3-Point Boundary Value Analysis (BVA),
and persistent state/quota read-backs on success and rejection.
"""
import copy
import uuid
import pytest
import requests

class TestOrderCreationAPI:
    """Verifies Workflow A order placement across Equivalence Partitions and BVA boundaries."""

    @staticmethod
    def get_case(generated_data, partition_name, case_id):
        """Helper to retrieve vector from generator dataset by case_id."""
        for case in generated_data["equivalence_partitions"][partition_name]:
            if case["case_id"] == case_id:
                return case
        raise KeyError(f"Case ID '{case_id}' not found in partition '{partition_name}'")

    def test_ep_val_01_single_ticket(self, event_endpoints, admin_headers, generated_data):
        """TC-API-01: Valid single ticket purchase (EP-VAL-01). Expected: HTTP 201 + Quota decremented by 1."""
        case = self.get_case(generated_data, "valid_partition", "EP-VAL-01")
        orders_url = event_endpoints["orders"]
        quotas_url = event_endpoints["quotas"]

        # 1. Pre-execution quota read-back
        q_init = requests.get(quotas_url, headers=admin_headers).json()["available_number"]

        # 2. Execute order using generator payload with unique email to avoid collision
        payload = copy.deepcopy(case["payload"])
        payload["email"] = f"ep_val_01_{uuid.uuid4().hex[:6]}@example.com"

        resp = requests.post(orders_url, json=payload, headers=admin_headers)
        assert resp.status_code == 201 and resp.status_code == case["expected_status"], f"Expected {case['expected_status']}, got {resp.status_code}: {resp.text}"

        data = resp.json()
        assert "code" in data and len(data["code"]) == 5
        assert data["status"] == "n"  # Pending
        assert len(data["positions"]) == case["quantity"]

        # 3. Post-execution quota read-back: Headroom must decrement by exactly quantity
        q_post = requests.get(quotas_url, headers=admin_headers).json()["available_number"]
        assert q_post == q_init - case["quantity"], f"Quota mismatch: expected {q_init - case['quantity']}, got {q_post}"

